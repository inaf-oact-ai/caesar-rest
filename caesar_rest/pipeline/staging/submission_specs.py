"""Server-side, single-input staged-container submission specifications.

Only call after ordinary application validation and dataset authorization. This
module is a trusted adapter, not a client-writable execution-spec endpoint.
"""
import json
import os
import re
from pathlib import Path


class PipelineSubmissionError(ValueError):
	pass


def _clean_path(value, label):
	if not isinstance(value, str) or not value.startswith('/') or any(c in value for c in '\x00\r\n'):
		raise PipelineSubmissionError('%s must be an absolute clean path' % label)
	if '//' in value or any(p in ('.', '..') for p in value.split('/')) or (len(value) > 1 and value.endswith('/')):
		raise PipelineSubmissionError('%s must be normalized' % label)
	return value


def _under(path, root):
	return path == root or path.startswith(root.rstrip('/') + '/')


def _translate(path, app_root, cluster_root):
	_clean_path(path, 'Source path')
	_clean_path(app_root, 'Application root')
	_clean_path(cluster_root, 'Cluster root')
	if not _under(path, app_root):
		raise PipelineSubmissionError('Source is outside configured application root')
	return cluster_root + path[len(app_root):] if app_root != '/' else cluster_root.rstrip('/') + path

 
def create_specs(
	workspace_app,
	workspace_cluster,
	inputfile,
	cmd_arg_list,
	image,
	app_data_root,
	cluster_data_root,
	app_job_root,
	cluster_job_root,
	model_dir=None,
	app_mode='',
	input_mode='copy'
):
	"""Build trusted generic PREPARE and EXECUTE specs, with one mapped input.

	Current restricted adapter: one source and exactly one ordinary --key=<path>
	input argument already generated by the app configurator. Future multi-input
	binding should be a separate explicit input contract, not string replacement.
	"""
	
	# - Input strategy is selected by the trusted application
	#   configurator. The generic staging layer does not inspect
	#   scientific application names or processing stages.
	if input_mode not in ('copy', 'reference_ro'):
		raise PipelineSubmissionError(
			'Unsupported input staging mode: %s' % input_mode
	)
		
	for label, path in [('Workspace', workspace_app), ('Cluster workspace', workspace_cluster),
	                    ('Image', image), ('Input', inputfile)]:
		_clean_path(path, label)
	
	if not _under(workspace_app, app_job_root) or workspace_app == app_job_root:
		raise PipelineSubmissionError('Workspace must be below application job root')
		
	if not _under(workspace_cluster, cluster_job_root) or workspace_cluster == cluster_job_root:
		raise PipelineSubmissionError('Workspace must be below cluster job root')
	
	if _translate(workspace_app, app_job_root, cluster_job_root) != workspace_cluster:
		raise PipelineSubmissionError('Workspace path mapping mismatch')
	
	if not isinstance(cmd_arg_list, (tuple, list)) or not cmd_arg_list:
		raise PipelineSubmissionError('Missing validated application arguments')

	# Accept only server-authorized paths in known, configured storage roots.
	if _under(inputfile, app_data_root):
		source = _translate(inputfile, app_data_root, cluster_data_root)
	elif _under(inputfile, app_job_root):
		source = _translate(inputfile, app_job_root, cluster_job_root)
	else:
		raise PipelineSubmissionError('Input is outside configured data and job roots')

	name = os.path.basename(inputfile)
	if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', name) or name == 'staging.json':
		raise PipelineSubmissionError('Unsupported staged input name')
	matches = []
	remaining = []
	for arg in cmd_arg_list:
		if not isinstance(arg, str) or not arg.startswith('--') or any(c.isspace() or c in "'\"\\$`\x00" for c in arg):
			raise PipelineSubmissionError('Invalid validated application argument')
		if '=' in arg:
			key, val = arg[2:].split('=', 1)
			if val == inputfile:
				if not re.fullmatch(r'[a-zA-Z][a-zA-Z0-9_-]*', key):
					raise PipelineSubmissionError('Invalid input option')
				matches.append(key)
				continue
		remaining.append(arg)
	if len(matches) != 1 or not remaining:
		raise PipelineSubmissionError('Exactly one input-path option is required')
	if any(arg.startswith('--' + matches[0] + '=') for arg in remaining):
		raise PipelineSubmissionError('Duplicate input option')
	if source == workspace_cluster or _under(source, workspace_cluster) or _under(workspace_cluster, source):
		raise PipelineSubmissionError('Input source overlaps workspace')
		
	environment = {}

	if model_dir:
		_clean_path(model_dir, 'Model directory')
		environment['MODEL_DIR'] = model_dir

	if app_mode:
		if not isinstance(app_mode, str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', app_mode):
			raise PipelineSubmissionError('Invalid application mode')
		environment['APP_MODE'] = app_mode
		
	return (
		{
			'version': 1,
			'inputs': [{
				'source': source,
				'name': name,
				'mode': input_mode,
				'writable': input_mode == 'copy'
			}]			
		},
		{
			'version': 1, 
			'image': image, 
			'container_workspace': workspace_app,
			'arguments': remaining, 
			'input_options': {
				matches[0]: name
			},
			'execution_dir': 'execution', 
			'output_dir': 'results', 
			'environment': environment
		}
	)


def write_specs(workspace_app, staging, execution):
	"""Write both specifications exclusively; never overwrite existing data."""
	base = Path(workspace_app)
	if not base.is_dir() or base.is_symlink() or str(base.resolve(strict=True)) != workspace_app:
		raise PipelineSubmissionError('Invalid existing private workspace')
	paths = (base / 'staging_spec.json', base / 'execution_spec.json')
	if any(p.exists() or p.is_symlink() for p in paths):
		raise PipelineSubmissionError('Specification already exists')
	created = []
	try:
		for path, content in zip(paths, (staging, execution)):
			fd = os.open(str(path), os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
			created.append(path)
			with os.fdopen(fd, 'w', encoding='utf8') as f:
				json.dump(content, f, indent=2)
				f.write('\n')
	except Exception:
		for path in created:
			path.unlink(missing_ok=True)
		raise
	return tuple(str(p) for p in paths)
